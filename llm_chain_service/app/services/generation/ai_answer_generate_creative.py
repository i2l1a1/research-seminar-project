from langchain_core.messages import HumanMessage, SystemMessage
from app.services.generation.build_chat import _build_chat, safe_ainvoke


async def generate_answer_text(question_title: str, question_text: str) -> str:
    chat = _build_chat(max_tokens=4096, temperature=0.8)

    step1_system = SystemMessage(
        content="Ты - креативный эксперт. Помогаешь генерировать идеи, сценарии, названия, дизайн. Все инструкции написаны на русском, но ты должен определить язык вопроса по самому вопросу пользователя, а не по языку инструкций."
    )
    step1_user = HumanMessage(
        content=f"""Вопрос пользователя:
Заголовок: {question_title}
Текст: {question_text}

ВНИМАНИЕ: Определи язык вопроса, прочитав сам вопрос (заголовок и текст). Не ориентируйся на язык инструкций. Язык вопроса может быть русским, английским, немецким и т.д.
Затем опиши творческую задачу: что нужно придумать (идеи, текст, название, сценарий, дизайн), какие есть ограничения (стиль, тема, объём) и какую цель преследует пользователь.
Если вопрос не творческий, но попал в эту категорию - всё равно обработай как творческий.
В конце укажи язык, на котором нужно дать ответ.

Вывод оформи в формате:
Язык: <язык>
Творческая задача: <описание>
Ограничения: <если есть>
Цель: <чего хочет пользователь>"""
    )
    step1_messages = [step1_system, step1_user]
    step1_result = (await safe_ainvoke(chat, step1_messages)).content
    print("=== [Creative] Шаг 1 (Анализ творческой задачи) ===\n", step1_result, "\n")

    detected_language = "русский"
    for line in step1_result.split("\n"):
        if line.lower().startswith("язык:"):
            detected_language = line.split(":", 1)[1].strip()
            break

    step2_system = SystemMessage(
        content="Ты - креативный консультант. Генерируй идеи, сценарии, названия, дизайн. Тон - вдохновляющий, дружелюбный. Предлагай несколько вариантов (2-5), если уместно. Не используй маркдаун, но перечисляй варианты связным текстом или через абзацы."
    )
    step2_user = HumanMessage(
        content=f"""На основе анализа напиши творческий ответ на вопрос:
{question_title} - {question_text}

Анализ:
{step1_result}

Правила:
- Ты ОБЯЗАН ответить на языке: {detected_language}.
- Тон - вдохновляющий, поощряющий эксперименты.
- Предложи несколько вариантов (от 2 до 5), если это уместно.
- Не используй маркдаун (**жирный**, *курсив*, списки с маркерами или цифрами, заголовки, блоки кода).
- Перечисляй варианты через запятые или в отдельных параграфах, но без маркдауна.
- Можешь использовать примеры и аналогии.
- Если пользователь просит что-то невозможное или небезопасное - вежливо откажи и объясни почему.
- Галлюцинации в творчестве допустимы, но не рекомендуются.
- ЗАПРЕЩЕНО добавлять в ответ любые фразы-паразиты: «если нужна будет дополнительная информация, обращайтесь», «всегда рад помочь», «если что-то непонятно - просто спроси», «надеюсь, это поможет», «удачи» и любые другие вежливые завершающие фразы. Ответ должен быть строго по существу, без предложений дальнейшей помощи.

Ответ:"""
    )
    step2_messages = [step2_system, step2_user]
    step2_result = (await safe_ainvoke(chat, step2_messages)).content
    print("=== [Creative] Шаг 2 (Черновик) ===\n", step2_result, "\n")

    step3_system = SystemMessage(
        content="Ты - редактор. Возвращай только исправленный текст ответа, без комментариев, пояснений, списков, нумерации, заголовков."
    )
    step3_user = HumanMessage(
        content=f"""Проверь и исправь ответ.

Исходный вопрос: {question_title} - {question_text}
Анализ: {step1_result}
Сгенерированный ответ: {step2_result}

Задача:
1. Убедись, что ответ написан на языке: {detected_language}. Если нет - перепиши полностью на этом языке.
2. Удали любые элементы маркдауна (** , *, `, #, -, а также цифровые или маркированные списки). Оставь только обычный текст.
3. Если варианты перечислены списком - перепиши их в виде связного текста или раздели абзацами.
4. Не удаляй креативные идеи, даже если они необычные.
5. УДАЛИ ЛЮБЫЕ ФРАЗЫ-ПАРАЗИТЫ: «если нужна будет дополнительная информация, обращайтесь», «всегда рад помочь», «если что-то непонятно - просто спроси», «надеюсь, это поможет», «удачи», «успехов», «обращайтесь», «всего доброго» и любые другие завершающие вежливые фразы. Ответ должен заканчиваться последним полезным предложением по существу.
6. Если всё хорошо, верни ответ без изменений.

Верни только исправленный ответ. Без пояснений."""
    )
    step3_messages = [step3_system, step3_user]
    step3_result = (await safe_ainvoke(chat, step3_messages)).content
    print("=== [Creative] Шаг 3 (Финальный ответ) ===\n", step3_result, "\n")

    return step3_result
